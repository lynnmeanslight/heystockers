import { writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';

const ISSUER_URL = 'https://api.backed.fi/api/v1/token?type=xstocks';
const DEX_URL = 'https://api.dexscreener.com/tokens/v1/solana';
const LIMIT = 50;
const BATCH_SIZE = 30;

async function fetchJson(url, init, attempts = 3) {
  for (let attempt = 1; attempt <= attempts; attempt += 1) {
    const response = await fetch(url, init);
    if (response.ok) return response.json();
    if (attempt === attempts || response.status < 500) throw new Error(`${url} returned ${response.status}`);
    await new Promise((resolveDelay) => setTimeout(resolveDelay, attempt * 750));
  }
  throw new Error(`${url} could not be reached`);
}

function chunks(values, size) {
  return Array.from({ length: Math.ceil(values.length / size) }, (_, index) => values.slice(index * size, (index + 1) * size));
}

function assetType(name, symbol) {
  const knownEtfs = new Set(['SPYx', 'QQQx', 'GLDx', 'SLVx', 'TQQQx', 'IWMx', 'VTIx', 'VOOx', 'ARKKx']);
  return knownEtfs.has(symbol) || /(ETF|Trust|Fund|Portfolio|Index|S&P|Nasdaq|iShares|Invesco|SPDR|Vanguard|VanEck|WisdomTree|Direxion|ProShares|Global X)/i.test(name)
    ? 'ETF'
    : 'STOCK';
}

function generatedModule(assets) {
  return `// Generated by scripts/refresh-stock-catalog.mjs. Do not edit by hand.\nexport const GENERATED_TRADE_ASSETS = ${JSON.stringify(assets, null, 2)} as const;\n`;
}

const issuer = await fetchJson(ISSUER_URL);
const official = issuer.nodes
  .filter((token) => !token.isTradingHalted)
  .map((token) => {
    const deployment = token.deployments.find((candidate) => candidate.network === 'Solana');
    const mint = deployment?.address?.replace(/^svm:/, '');
    return mint
      ? {
          symbol: token.symbol,
          shortName: token.name.replace(/ xStock$/i, ''),
          name: token.name,
          logo: token.logo,
          type: assetType(token.name, token.symbol),
          mint,
          decimals: 8,
        }
      : null;
  })
  .filter(Boolean);

const byMint = new Map(official.map((asset) => [asset.mint, { asset, volume24h: 0, price: null, bestLiquidity: -1, pairs: new Set() }]));
const requests = chunks(official.map((asset) => asset.mint), BATCH_SIZE).map((batch) =>
  fetchJson(`${DEX_URL}/${batch.join(',')}`),
);
const pairGroups = await Promise.all(requests);

for (const pairs of pairGroups) {
  for (const pair of pairs) {
    for (const side of ['baseToken', 'quoteToken']) {
      const mint = pair[side]?.address;
      const market = byMint.get(mint);
      if (!market || market.pairs.has(pair.pairAddress)) continue;
      market.pairs.add(pair.pairAddress);
      market.volume24h += Number(pair.volume?.h24) || 0;
      const liquidity = Number(pair.liquidity?.usd) || 0;
      if (side === 'baseToken' && liquidity > market.bestLiquidity && Number(pair.priceUsd) > 0) {
        market.bestLiquidity = liquidity;
        market.price = Number(pair.priceUsd);
      }
    }
  }
}

const top = [...byMint.values()]
  .filter((market) => market.price !== null && market.volume24h > 0)
  .sort((left, right) => right.volume24h - left.volume24h)
  .slice(0, LIMIT)
  .map(({ asset, volume24h, price }) => ({
    ...asset,
    referencePrice: Number(price.toFixed(6)),
    volume24h: Number(volume24h.toFixed(2)),
  }));

if (top.length === 0) throw new Error('No eligible Solana assets reported live volume');

const moduleText = generatedModule(top);
await Promise.all([
  writeFile(resolve('backend/src/catalog.generated.ts'), moduleText),
  writeFile(resolve('web/lib/catalog.generated.ts'), moduleText),
  writeFile(resolve('mobile/features/heystockers/catalog.generated.ts'), moduleText),
]);

console.log(JSON.stringify({
  officialSolanaAssets: issuer.nodes.length,
  eligibleSolanaAssets: official.length,
  selected: top.length,
  top: top.slice(0, 10).map(({ symbol, volume24h }) => ({ symbol, volume24h })),
}, null, 2));
