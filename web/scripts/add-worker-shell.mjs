// Generates dist/server/worker-shell.js, a wrapper entry that enforces the
// security headers on every worker response. Needed because vinext's
// Cloudflare entry currently ignores next.config.ts headers() (beta gap).
// Keep this header list in sync with web/next.config.ts securityHeaders.
import { existsSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const serverDir = join(dirname(fileURLToPath(import.meta.url)), '..', 'dist', 'server');
if (!existsSync(join(serverDir, 'index.js'))) {
  console.error('dist/server/index.js not found. Run the build before add-worker-shell.');
  process.exit(1);
}

const headers = {
  'X-Content-Type-Options': 'nosniff',
  'X-Frame-Options': 'DENY',
  'Referrer-Policy': 'strict-origin-when-cross-origin',
  'Permissions-Policy': 'camera=(), microphone=(), geolocation=(), payment=()',
  'Strict-Transport-Security': 'max-age=31536000; includeSubDomains',
  'Content-Security-Policy': [
    "default-src 'self'",
    "script-src 'self' 'unsafe-inline'",
    "style-src 'self' 'unsafe-inline'",
    // Google's s2/favicons endpoint 301s to *.gstatic.com; CSP checks every redirect hop.
    "img-src 'self' data: https://xstocks-metadata.backed.fi https://www.google.com https://*.gstatic.com",
    "connect-src 'self' https://api.heystockers.trade",
    "font-src 'self' data:",
    "object-src 'none'",
    "base-uri 'self'",
    "form-action 'self'",
    "frame-ancestors 'none'",
  ].join('; '),
};

const shell = `// Generated by scripts/add-worker-shell.mjs. Do not edit.
import handler from './index.js';

const SECURITY_HEADERS = ${JSON.stringify(headers, null, 2)};

export default {
  ...handler,
  async fetch(request, env, ctx) {
    const response = await handler.fetch(request, env, ctx);
    if (response.status === 101) return response;
    const headers = new Headers(response.headers);
    for (const [key, value] of Object.entries(SECURITY_HEADERS)) {
      if (!headers.has(key)) headers.set(key, value);
    }
    return new Response(response.body, { status: response.status, statusText: response.statusText, headers });
  },
};
`;

writeFileSync(join(serverDir, 'worker-shell.js'), shell);
console.log('Wrote dist/server/worker-shell.js with enforced security headers.');
